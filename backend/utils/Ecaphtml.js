/**
 * Escapes HTML special characters so user-submitted text can be safely
 * interpolated into email HTML without breaking markup or allowing
 * injection.
 */
function escapeHtml(str = '') {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

module.exports = { escapeHtml };